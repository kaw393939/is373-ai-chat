@contextlib.contextmanager
def postgres():
    """Own a new labeled container; cleanup only its returned immutable ID."""
    local_docker()
    token = uuid4().hex
    image = re.search(r"image:\s*(postgres:\S+)", (ROOT / "compose.yaml").read_text())[1]
    result = run(
        "docker",
        "run",
        "-d",
        "--rm",
        "--label",
        f"is373.book-lab={token}",
        "--memory",
        "256m",
        "--cpus",
        "0.50",
        "--pids-limit",
        "128",
        "-p",
        "127.0.0.1::5432",
        "-e",
        "POSTGRES_USER=lab",
        "-e",
        "POSTGRES_PASSWORD=synthetic-local-lab",
        "-e",
        "POSTGRES_DB=lab_test",
        image,
        capture_output=True,
        text=True,
    )
    container = result.stdout.strip()
    if not re.fullmatch(r"[0-9a-f]{64}", container):
        raise RuntimeError("Docker did not return a container ID")
    try:
        for _ in range(40):
            ready = subprocess.run(
                ["docker", "exec", container, "pg_isready", "-U", "lab", "-d", "lab_test"],
                capture_output=True,
            )
            if ready.returncode == 0:
                break
            time.sleep(0.5)
        else:
            raise RuntimeError("Disposable PostgreSQL did not become ready")
        port = run(
            "docker", "port", container, "5432", capture_output=True, text=True
        ).stdout.strip()
        if not re.fullmatch(r"127\.0\.0\.1:\d+", port):
            raise RuntimeError("Expected a loopback-only port")
        url = f"postgresql+asyncpg://lab:synthetic-local-lab@{port}/lab_test"
        env = lab_environment(url)
        yield container, env
    finally:
        inspected = subprocess.run(
            [
                "docker",
                "inspect",
                "--format",
                '{{index .Config.Labels "is373.book-lab"}}',
                container,
            ],
            capture_output=True,
            text=True,
        )
        if inspected.returncode == 0 and inspected.stdout.strip() == token:
            # -v removes only anonymous volumes belonging to this new container.
            run("docker", "rm", "-f", "-v", container, capture_output=True)


