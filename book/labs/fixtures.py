def lab_environment(database_url):
    """Override every Settings field, including values in the user's .env."""
    from app.config import Settings

    settings = Settings(
        _env_file=None,
        **{name: field.default for name, field in Settings.model_fields.items()},
    )
    settings.database_url = database_url
    settings.jwt_secret = "synthetic-local-book-key-never-deploy-0000000000000000"
    settings.provider = "mock"
    settings.email_provider = "disabled"
    env = dict(os.environ)
    env.update({name.upper(): str(value) for name, value in settings.model_dump().items()})
    env.pop("TEST_DATABASE_URL", None)
    env.pop("TEST_ALLOW_RESET", None)
    return env


@contextlib.contextmanager
def process_environment(values):
    original = dict(os.environ)
    os.environ.clear()
    os.environ.update(values)
    try:
        yield
    finally:
        os.environ.clear()
        os.environ.update(original)


def migration():
    from alembic import command
    from alembic.config import Config
    from alembic.util.exc import AutogenerateDiffsDetected
    from sqlalchemy import Index

    from app.models import Base

    with tempfile.TemporaryDirectory(prefix="is373-migration-") as directory:
        path = Path(directory)
        shutil.copytree(ROOT / "migrations", path / "migrations")
        # SQLite reflects PostgreSQL Float/DOUBLE definitions differently. This
        # index-only experiment changes its private copy, never the CI contract.
        environment_file = path / "migrations" / "env.py"
        environment_file.write_text(
            environment_file.read_text().replace("compare_type=True", "compare_type=False")
        )
        config = Config(str(ROOT / "alembic.ini"))
        config.set_main_option("script_location", str(path / "migrations"))
        env = lab_environment(f"sqlite+aiosqlite:///{path / 'migration_test.db'}")
        with process_environment(env):
            command.upgrade(config, "head")
            table = Base.metadata.tables["conversations"]
            index = Index("ix_lab_conversations_title", table.c.title)
            try:
                command.revision(
                    config, message="lab additive title index", autogenerate=True, rev_id="lab0003"
                )
                command.upgrade(config, "head")
                command.check(config)
                with sqlite3.connect(path / "migration_test.db") as db:
                    assert (
                        db.execute("SELECT version_num FROM alembic_version").fetchone()[0]
                        == "lab0003"
                    )
                    assert "ix_lab_conversations_title" in {
                        row[1] for row in db.execute("PRAGMA index_list(conversations)")
                    }
                # Fixed fault: metadata and the database disagree in this process.
                table.indexes.remove(index)
                try:
                    command.check(config)
                except AutogenerateDiffsDetected:
                    print("Expected: model/schema drift detected")
                else:
                    raise AssertionError("Drift was not detected")
                table.indexes.add(index)
                command.check(config)
                print("Expected: additive index migrated; index comparison has no drift")
                generated = next((path / "migrations" / "versions").glob("lab0003_*.py"))
                print(generated.read_text())
            finally:
                table.indexes.discard(index)


async def stream():
    import codecs

    import httpx

    from app.config import Settings
    from app.providers import HTTPProvider

    values = {name: field.default for name, field in Settings.model_fields.items()}
    values.update(
        provider="openai",
        openai_api_key="synthetic-never-sent",
        email_provider="disabled",
        app_env="development",
    )
    settings = Settings(_env_file=None, **values)
    complete = (
        'data: {"type":"response.output_text.delta","delta":"hello"}\n\n'
        + 'data: {"type":"response.completed","response":{"usage":{"total_tokens":2}}}\n\n'
    )
    real_client = httpx.AsyncClient

    async def normalized(body):
        with patch(
            "app.providers.httpx.AsyncClient",
            lambda **kw: real_client(
                transport=httpx.MockTransport(lambda request: httpx.Response(200, text=body)), **kw
            ),
        ):
            return [item async for item in HTTPProvider(settings).stream([], 64)]

    assert await normalized(complete) == [{"text": "hello"}, {"tokens": 2}]
    truncated = await normalized(complete.split('data: {"type":"response.completed"')[0])
    assert truncated == [{"text": "hello"}]
    print("Observed gap: premature EOF produces text without a terminal usage event")
    wire = 'event: delta\ndata: {"text":"café"}\n\n'.encode()
    split = wire.index("é".encode()) + 1
    chunks = [wire[:split], wire[split:]]
    try:
        chunks[0].decode("utf-8")
    except UnicodeDecodeError:
        print("Expected: decoding each network chunk independently fails")
    else:
        raise AssertionError("The fixture did not split a multibyte character")
    decoder = codecs.getincrementaldecoder("utf-8")()
    text = "".join(
        decoder.decode(chunk, final=i == len(chunks) - 1) for i, chunk in enumerate(chunks)
    )
    assert "café" in text and text.endswith("\n\n")
    print("Expected: incremental decoder retains the complete Unicode frame")


def coverage():
    import coverage as coverage_tool

    with tempfile.TemporaryDirectory(prefix="is373-coverage-") as directory:
        file = Path(directory) / "policy.py"
        # This mutant is intentionally wrong; it is never installed in app/.
        file.write_text("def allowed(owner, caller):\n    return True\n")
        measured = coverage_tool.Coverage(branch=True, source=[directory], data_file=None)
        measured.start()
        spec = importlib.util.spec_from_file_location("lab_policy", file)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        assert module.allowed("alice", "alice")  # Weak positive-only example.
        measured.stop()
        assert measured.report() == 100
        try:
            assert not module.allowed("alice", "bob")
        except AssertionError:
            print("Expected: 100% measured coverage; negative ownership example rejects mutant")
        else:
            raise AssertionError("Negative assertion failed to detect the mutant")


def promotion():
    digest = "sha256:" + "a" * 64
    accepted = {"commit": "b" * 40, "digest": digest, "schema": "0002", "checks": "passed"}

    def permit(candidate, qa, approval):
        if not approval or qa["checks"] != "passed":
            raise ValueError("Approval and passing QA evidence required")
        if any(candidate[key] != qa[key] for key in ("commit", "digest", "schema")):
            raise ValueError("Candidate differs from accepted QA artifact")
        return dict(candidate)

    assert permit(accepted, accepted, True) == accepted
    for candidate, qa, approval in [
        ({**accepted, "digest": "sha256:" + "c" * 64}, accepted, True),
        (accepted, {**accepted, "checks": "failed"}, True),
        (accepted, accepted, False),
    ]:
        try:
            permit(candidate, qa, approval)
        except ValueError as failure:
            print("Expected rejection:", failure)
        else:
            raise AssertionError("Unsafe proposal was accepted")
    print("Expected: same accepted artifact plus approval passes the local policy model")
    print("This is a decision model, not the implemented production promotion gate.")


def local_docker():
    context = os.environ.get("DOCKER_CONTEXT")
    if context:
        endpoint = run(
            "docker",
            "context",
            "inspect",
            context,
            "--format",
            "{{.Endpoints.docker.Host}}",
            capture_output=True,
            text=True,
        ).stdout.strip()
    else:
        endpoint = (
            os.environ.get("DOCKER_HOST")
            or run(
                "docker",
                "context",
                "inspect",
                "--format",
                "{{.Endpoints.docker.Host}}",
                capture_output=True,
                text=True,
            ).stdout.strip()
        )
    if not endpoint.startswith(("unix://", "npipe://")):
        raise RuntimeError("Use a local Docker socket, not a remote/cloud Docker daemon")
    # Freeze the checked endpoint for later CLI calls, regardless of context.
    os.environ.pop("DOCKER_CONTEXT", None)
    os.environ["DOCKER_HOST"] = endpoint


def image():
    local_docker()
    if run("git", "status", "--porcelain", capture_output=True, text=True).stdout.strip():
        raise RuntimeError(
            "Build from a clean book-edition checkout; inspect/save your lab changes first"
        )
    commit = run("git", "rev-parse", "HEAD", capture_output=True, text=True).stdout.strip()
    tag = "is373-book-lab:" + uuid4().hex
    try:
        run(
            "docker",
            "build",
            "--platform",
            "linux/amd64",
            "--build-arg",
            f"COMMIT_SHA={commit}",
            "-t",
            tag,
            ".",
        )
        data = json.loads(
            run("docker", "image", "inspect", tag, capture_output=True, text=True).stdout
        )[0]
        actual = data["Config"]["Labels"]["org.opencontainers.image.revision"]
        assert actual == commit and data["Config"]["User"] == "10001:10001"
        print("Verified source label:", actual)
        print("Local image content ID:", data["Id"])
        assert actual != "0" * 40
        print("Expected: deliberately mismatched source claim rejected")
        print("Local image ID is not evidence of a published registry manifest digest.")
    finally:
        subprocess.run(["docker", "image", "rm", tag], capture_output=True)


