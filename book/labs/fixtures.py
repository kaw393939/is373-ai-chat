def recovery():
    with postgres() as (container, env):
        run(sys.executable, "-m", "alembic", "upgrade", "head", env=env)
        run(
            sys.executable,
            "-m",
            "app.cli",
            "admin",
            env={**env, "ADMIN_PASSWORD": "synthetic-local-book-password-123"},
        )
        limits = json.loads(
            run("docker", "inspect", container, capture_output=True, text=True).stdout
        )[0]["HostConfig"]
        assert limits["Memory"] == 256 * 1024 * 1024 and limits["PidsLimit"] == 128
        print("Verified limits: memory=256MiB pids=128 cpu=0.50")
        print(
            run(
                "docker",
                "stats",
                "--no-stream",
                "--format",
                "{{.MemUsage}}",
                container,
                capture_output=True,
                text=True,
            ).stdout.strip()
        )
        dump = run(
            "docker",
            "exec",
            container,
            "pg_dump",
            "-U",
            "lab",
            "-Fc",
            "lab_test",
            capture_output=True,
        ).stdout
        run(
            "docker",
            "exec",
            container,
            "psql",
            "-U",
            "lab",
            "-d",
            "lab_test",
            "-c",
            "TRUNCATE users CASCADE",
            capture_output=True,
        )
        run("docker", "exec", container, "createdb", "-U", "lab", "restore_test")
        run(
            "docker",
            "exec",
            "-i",
            container,
            "pg_restore",
            "--exit-on-error",
            "-U",
            "lab",
            "-d",
            "restore_test",
            input=dump,
            capture_output=True,
        )

        def scalar(database, sql):
            return run(
                "docker",
                "exec",
                container,
                "psql",
                "-U",
                "lab",
                "-d",
                database,
                "-Atc",
                sql,
                capture_output=True,
                text=True,
            ).stdout.strip()

        assert scalar("lab_test", "SELECT count(*) FROM users") == "0"
        assert scalar("restore_test", "SELECT count(*) FROM users") == "1"
        schema = scalar("restore_test", "SELECT version_num FROM alembic_version")
        assert schema == "0002"
        print(f"Expected: original users=0; restored users=1; restored schema={schema}")
        print("Local restoration evidence does not prove off-host disaster recovery.")


